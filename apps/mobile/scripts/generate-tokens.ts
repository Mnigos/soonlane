import { dirname, join } from 'node:path'

const REM_PX = 16
const OUTPUT = join(import.meta.dir, '../src/tokens.gen.ts')
const TOKENS_CSS = Bun.resolveSync(
	'@soonlane/tailwind-config/tokens',
	import.meta.dir
)
const TAILWIND_THEME_CSS = Bun.resolveSync(
	'tailwindcss/theme.css',
	dirname(TOKENS_CSS)
)

function readDeclarations(css: string) {
	return new Map(
		[...css.matchAll(/--([\w-]+):\s*([^;]+);/gu)].map(
			([, name = '', value = '']) => [name, value.trim()]
		)
	)
}

const tokens = readDeclarations(await Bun.file(TOKENS_CSS).text())
const declarations = new Map([
	...readDeclarations(await Bun.file(TAILWIND_THEME_CSS).text()),
	...tokens,
])

function resolve(value = ''): string {
	const reference = /^var\(--([\w-]+)\)$/u.exec(value)?.[1]

	return reference ? resolve(declarations.get(reference)) : value
}

function toPx(value: string) {
	const rem = /^([\d.]+)rem$/u.exec(value)?.[1]

	return rem ? Number(rem) * REM_PX : undefined
}

function toRatio(value: string) {
	const division = /^calc\(([\d.]+) \/ ([\d.]+)\)$/u.exec(value)

	if (division) return Number(division[1]) / Number(division[2])

	return /^[\d.]+$/u.test(value) ? Number(value) : undefined
}

function pickPrefixed(source: Map<string, string>, prefix: string) {
	return [...source.keys()]
		.filter(
			name =>
				name.startsWith(prefix) && !name.slice(prefix.length).includes('--')
		)
		.map(
			name => [name.slice(prefix.length), resolve(source.get(name))] as const
		)
}

function toTextStyle(name: string, size: string) {
	const fontSize = toPx(size)

	if (fontSize === undefined) return []

	const lineHeight = resolve(declarations.get(`text-${name}--line-height`))
	const lineHeightPx =
		toPx(lineHeight) ?? fontSize * (toRatio(lineHeight) ?? Number.NaN)

	if (Number.isNaN(lineHeightPx)) return []

	return [
		[
			name,
			{ fontSize, lineHeight: Math.round(lineHeightPx * 100) / 100 },
		] as const,
	]
}

function toConstant(
	name: string,
	entries: readonly (readonly [string, unknown])[]
) {
	const object = Object.fromEntries(
		entries.map(([key, value]) => [
			key.replaceAll(/-(\w)/gu, (_, letter: string) => letter.toUpperCase()),
			value,
		])
	)

	return `export const ${name} = ${JSON.stringify(object, undefined, '\t')} as const\n`
}

await Bun.write(
	OUTPUT,
	[
		'/** Generated by scripts/generate-tokens.ts from tooling/tailwind-config/tokens.css and Tailwind’s type scale; do not edit. */',
		toConstant(
			'COLORS',
			pickPrefixed(tokens, 'color-').filter(([, value]) =>
				value.startsWith('#')
			)
		),
		toConstant(
			'RADIUS',
			pickPrefixed(tokens, 'radius-').map(
				([name, value]) => [name, toPx(value)] as const
			)
		),
		toConstant(
			'TEXT',
			pickPrefixed(declarations, 'text-').flatMap(([name, size]) =>
				toTextStyle(name, size)
			)
		),
	].join('\n')
)
